# Compare integer and floating-point values

whole_litres = 6
measured_litres = 6.25
print("Whole litres:", whole_litres, type(whole_litres).__name__)
print("Measured litres:", measured_litres, type(measured_litres).__name__)
print("Half the whole-litre count:", whole_litres / 2)
print("Same value as a float:", whole_litres == 6.0)
